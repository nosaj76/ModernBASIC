use crate::{
    profile::{InstrumentBank, Trigger},
    synth, wav,
};
use std::{collections::BTreeMap, fs, io, path::Path};

fn round_robin_sequence(bank: &InstrumentBank, region: &crate::profile::Region) -> (usize, usize) {
    let mut values: Vec<u8> = bank
        .regions
        .iter()
        .filter(|candidate| {
            candidate.articulation == region.articulation
                && candidate.trigger == region.trigger
                && candidate.key_lo == region.key_lo
                && candidate.key_hi == region.key_hi
                && candidate.vel_lo == region.vel_lo
                && candidate.vel_hi == region.vel_hi
        })
        .map(|candidate| candidate.round_robin.max(1))
        .collect();
    values.sort_unstable();
    values.dedup();
    let position = values
        .binary_search(&region.round_robin.max(1))
        .map(|index| index + 1)
        .unwrap_or(1);
    (values.len().max(1), position)
}

pub fn write(bank: &InstrumentBank, path: impl AsRef<Path>) -> io::Result<()> {
    bank.validate()?;
    let path = path.as_ref();
    let stem = path
        .file_stem()
        .and_then(|value| value.to_str())
        .unwrap_or("instrument");
    let sample_folder_name = format!("{stem}_samples");
    let sample_dir = path.with_file_name(&sample_folder_name);
    fs::create_dir_all(&sample_dir)?;

    let mut articulations: Vec<String> = bank
        .regions
        .iter()
        .map(|region| region.articulation.clone())
        .collect();
    articulations.sort();
    articulations.dedup();
    if articulations.len() > 128 {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "SFZ export supports at most 128 articulation keyswitches",
        ));
    }
    if let Some(position) = articulations
        .iter()
        .position(|name| name == &bank.default_articulation)
    {
        articulations.swap(0, position);
    }
    let switches: BTreeMap<String, u8> = articulations
        .iter()
        .enumerate()
        .map(|(index, articulation)| {
            (
                articulation.clone(),
                u8::try_from(index).unwrap_or(u8::MAX).min(127),
            )
        })
        .collect();
    let uses_switches = articulations.len() > 1;

    let mut text = format!(
        "// Generated by Ruststrument Forge {}\n// {}\n",
        env!("CARGO_PKG_VERSION"),
        bank.name
    );
    if uses_switches {
        text.push_str(&format!(
            "<global> sw_lokey=0 sw_hikey={} sw_default={}\n",
            switches.values().copied().max().unwrap_or(0),
            switches[&bank.default_articulation]
        ));
    }

    for (index, region) in bank.regions.iter().enumerate() {
        let filename = format!("sample_{index:04}.wav");
        let baked = synth::bake_region(bank, index)?;
        wav::write(sample_dir.join(&filename), &baked)?;
        let (round_robin_count, round_robin_position) = round_robin_sequence(bank, region);

        text.push_str("\n<region>\n");
        text.push_str(&format!(
            "sample={sample_folder_name}/{filename}\n\
             lokey={} hikey={} lovel={} hivel={} pitch_keycenter={}\n",
            region.key_lo, region.key_hi, region.vel_lo, region.vel_hi, region.root_key
        ));
        if uses_switches {
            text.push_str(&format!(
                "sw_last={} sw_label={}\n",
                switches[&region.articulation], region.articulation
            ));
        }
        if round_robin_count > 1 {
            text.push_str(&format!(
                "seq_length={round_robin_count} seq_position={round_robin_position}\n"
            ));
        }
        if region.trigger == Trigger::Release {
            text.push_str("trigger=release\n");
        }
        if region.trigger == Trigger::Attack {
            if let (Some(start), Some(end)) = (region.loop_start, region.loop_end) {
                let correction = 2_f64.powf(-region.tune_cents as f64 / 1_200.0);
                let start = (start as f64 / correction).round() as usize;
                let end = (end as f64 / correction).round() as usize;
                if start + 2 <= end && end <= baked.samples.len() {
                    text.push_str(&format!(
                        "loop_mode=loop_continuous loop_start={start} loop_end={end}\n"
                    ));
                }
            }
        }
    }
    fs::write(path, text)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sparse_round_robins_export_as_contiguous_sequence_positions() {
        let source = wav::Wav {
            sample_rate: 44_100,
            samples: (0..4_410)
                .map(|index| (std::f32::consts::TAU * 220.0 * index as f32 / 44_100.0).sin())
                .collect(),
        };
        let mut bank = InstrumentBank::single("test instrument", &source);
        bank.regions[0].round_robin = 1;
        let mut third = bank.regions[0].clone();
        third.round_robin = 3;
        bank.regions.push(third);

        assert_eq!(round_robin_sequence(&bank, &bank.regions[0]), (2, 1));
        assert_eq!(round_robin_sequence(&bank, &bank.regions[1]), (2, 2));
    }
}
